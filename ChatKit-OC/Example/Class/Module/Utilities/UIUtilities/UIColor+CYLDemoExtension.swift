import UIKit

extension UIColor {

    // MARK: - Gray

    /// Light gray default background.
    class func cylDemoColorGrayBG() -> UIColor {
        return UIColor(red: 239.0 / 255.0, green: 239.0 / 255.0, blue: 244.0 / 255.0, alpha: 1.0)
    }

    class func cylDemoColorGrayLine() -> UIColor {
        return UIColor(white: 0.5, alpha: 0.3)
    }
}
